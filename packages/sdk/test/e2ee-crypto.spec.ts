/**
 * @jest-environment node
 *
 * E2EE crypto: key schedule, frame format and the receive-side ratchet
 * window (docs/architecture/phase5-contracts.md §3).
 *
 * The fixed vectors live in docs/architecture/e2ee-vectors.json so the
 * Flutter, iOS and Android SDKs check themselves against the same bytes.
 * Regenerate (only when the format deliberately changes) with
 * `WRITE_E2EE_VECTORS=1 pnpm jest e2ee-crypto`.
 */
import { webcrypto } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

if (!(globalThis as { crypto?: { subtle?: unknown } }).crypto?.subtle) {
  Object.defineProperty(globalThis, 'crypto', { value: webcrypto, configurable: true });
}

import {
  decryptParsedFrame,
  deriveAesKeyBytes,
  deriveKeySet,
  deriveMaterialFromPassphrase,
  encryptFrame,
  fromHex,
  h264UnencryptedBytes,
  makeIv,
  needsRbspUnescaping,
  parseEncryptedFrame,
  parseRbsp,
  ratchetMaterial,
  toHex,
  unencryptedBytes,
  writeRbsp,
  type E2EECodec,
} from '../src/e2ee/crypto';
import { FrameCryptorCore, type E2EEState } from '../src/e2ee/frame-cryptor';
import { codecFromMimeType, payloadTypesFromSdp } from '../src/e2ee/worker-protocol';

const VECTORS_PATH = join(__dirname, '..', '..', '..', 'docs', 'architecture', 'e2ee-vectors.json');

const PASSPHRASE = 'correct horse battery staple';
const ROOM_ID = 'room_e2ee_vectors';
const RAW_KEY_HEX = '000102030405060708090a0b0c0d0e0f101112131415161718191a1b1c1d1e1f';

interface FrameCase {
  name: string;
  codec: E2EECodec;
  isKeyFrame: boolean;
  keyIndex: number;
  ssrc: number;
  timestamp: number;
  sendCount: number;
  plaintext: string;
}

const PAYLOAD = '0011223344556677889900aabbccddeeff0123456789abcdef00000102030405';
const FRAME_CASES: FrameCase[] = [
  {
    name: 'vp8-key',
    codec: 'vp8',
    isKeyFrame: true,
    keyIndex: 0,
    ssrc: 0x11223344,
    timestamp: 90000,
    sendCount: 0,
    plaintext: '5003009d012a8002e001' + PAYLOAD,
  },
  {
    name: 'vp8-delta',
    codec: 'vp8',
    isKeyFrame: false,
    keyIndex: 0,
    ssrc: 0x11223344,
    timestamp: 93000,
    sendCount: 1,
    plaintext: '310100' + PAYLOAD,
  },
  {
    name: 'h264-idr',
    codec: 'h264',
    isKeyFrame: true,
    keyIndex: 1,
    ssrc: 0x55667788,
    timestamp: 180000,
    sendCount: 7,
    // SPS, PPS, then an IDR slice: everything up to the IDR header + 1 byte stays clear.
    plaintext: '000000016742c01fda0140' + '0000000168ce3c80' + '0000000165888400' + PAYLOAD,
  },
  {
    name: 'opus',
    codec: 'opus',
    isKeyFrame: false,
    keyIndex: 0,
    ssrc: 0x0a0b0c0d,
    timestamp: 48000,
    sendCount: 3,
    plaintext: 'fc' + PAYLOAD,
  },
  {
    name: 'vp9',
    codec: 'vp9',
    isKeyFrame: true,
    keyIndex: 2,
    ssrc: 0x01020304,
    timestamp: 1234567,
    sendCount: 42,
    plaintext: '82498342' + PAYLOAD,
  },
];

async function buildVectors(): Promise<Record<string, unknown>> {
  const material = await deriveMaterialFromPassphrase(PASSPHRASE, ROOM_ID);
  const ratchet1 = await ratchetMaterial(material);
  const ratchet2 = await ratchetMaterial(ratchet1);
  const raw = fromHex(RAW_KEY_HEX);
  const keySet = await deriveKeySet(material);
  const frames = [];
  for (const frame of FRAME_CASES) {
    const iv = makeIv(frame.ssrc, frame.timestamp, frame.sendCount);
    const plain = fromHex(frame.plaintext);
    const encrypted = await encryptFrame(plain, frame, keySet, frame.keyIndex, iv);
    frames.push({
      ...frame,
      unencryptedBytes: unencryptedBytes(frame.codec, plain, frame.isKeyFrame),
      iv: toHex(iv),
      encrypted: toHex(encrypted),
    });
  }
  return {
    description:
      'Livqeno E2EE test vectors (docs/architecture/phase5-contracts.md §3). Generated by packages/sdk/test/e2ee-crypto.spec.ts; every SDK must reproduce them byte for byte.',
    keySchedule: {
      passphraseToMaterial:
        'PBKDF2-HMAC-SHA256(password = utf8(passphrase), salt = utf8("LivqenoE2EE:" + roomId), iterations = 100000, length = 32 bytes)',
      materialToAesKey:
        'HKDF-SHA256(ikm = material, salt = utf8("LivqenoRatchet"), info = 128 zero bytes, length = 16 bytes) — libwebrtc FrameCryptor with keyDerivationAlgorithm = HKDF, ratchetSalt = "LivqenoRatchet"',
      ratchet:
        'material\' = HKDF-SHA256(ikm = material, salt = utf8("LivqenoRatchet"), info = 128 zero bytes, length = 32 bytes)',
      iv: 'ssrc(4, BE) || rtpTimestamp(4, BE) || (rtpTimestamp - (sendCount mod 0xFFFF)) mod 2^32 (4, BE)',
      frame:
        '[clear header][AES-GCM-128 ciphertext][16-byte tag][12-byte IV][0x0c][keyIndex]; AAD = clear header; H.264: everything after the header is RBSP-escaped',
    },
    passphrase: {
      passphrase: PASSPHRASE,
      roomId: ROOM_ID,
      salt: `LivqenoE2EE:${ROOM_ID}`,
      material: toHex(material),
      aesKey: toHex(await deriveAesKeyBytes(material)),
    },
    ratchet: {
      from: toHex(material),
      steps: [
        { material: toHex(ratchet1), aesKey: toHex(await deriveAesKeyBytes(ratchet1)) },
        { material: toHex(ratchet2), aesKey: toHex(await deriveAesKeyBytes(ratchet2)) },
      ],
    },
    rawKey: { material: RAW_KEY_HEX, aesKey: toHex(await deriveAesKeyBytes(raw)) },
    frames: {
      keyMaterial: toHex(material),
      cases: frames,
    },
  };
}

describe('E2EE test vectors', () => {
  it('match docs/architecture/e2ee-vectors.json', async () => {
    const vectors = await buildVectors();
    if (process.env.WRITE_E2EE_VECTORS === '1' || !existsSync(VECTORS_PATH)) {
      writeFileSync(VECTORS_PATH, JSON.stringify(vectors, null, 2) + '\n');
    }
    const onDisk = JSON.parse(readFileSync(VECTORS_PATH, 'utf8'));
    expect(vectors).toEqual(onDisk);
  });

  it('decrypts every vector back to its plaintext', async () => {
    const onDisk = JSON.parse(readFileSync(VECTORS_PATH, 'utf8'));
    const keySet = await deriveKeySet(fromHex(onDisk.frames.keyMaterial));
    for (const frame of onDisk.frames.cases) {
      const parsed = parseEncryptedFrame(fromHex(frame.encrypted), frame);
      expect(parsed).toBeDefined();
      expect(parsed!.keyIndex).toBe(frame.keyIndex);
      expect(toHex(parsed!.iv)).toBe(frame.iv);
      expect(toHex(await decryptParsedFrame(parsed!, keySet))).toBe(frame.plaintext);
    }
  });
});

describe('frame format', () => {
  it('keeps the clear header and appends tag, IV, IV length and key index', async () => {
    const keySet = await deriveKeySet(fromHex(RAW_KEY_HEX));
    const plain = fromHex('310100' + PAYLOAD);
    const iv = makeIv(1, 2, 0);
    const out = await encryptFrame(plain, { codec: 'vp8', isKeyFrame: false }, keySet, 5, iv);
    expect(toHex(out.subarray(0, 3))).toBe('310100');
    expect(out.length).toBe(plain.length + 16 + 12 + 2);
    expect(out[out.length - 2]).toBe(12);
    expect(out[out.length - 1]).toBe(5);
    expect(toHex(out.subarray(out.length - 14, out.length - 2))).toBe(toHex(iv));
  });

  it('authenticates the clear header (AAD)', async () => {
    const keySet = await deriveKeySet(fromHex(RAW_KEY_HEX));
    const out = await encryptFrame(
      fromHex('fc' + PAYLOAD),
      { codec: 'opus', isKeyFrame: false },
      keySet,
      0,
      makeIv(1, 2, 3),
    );
    out[0] ^= 0x01;
    const parsed = parseEncryptedFrame(out, { codec: 'opus', isKeyFrame: false })!;
    await expect(decryptParsedFrame(parsed, keySet)).rejects.toBeDefined();
  });

  it('builds the IV from ssrc, timestamp and the send counter', () => {
    expect(toHex(makeIv(0x11223344, 0x00015f90, 0))).toBe('1122334400015f9000015f90');
    expect(toHex(makeIv(1, 5, 7))).toBe('0000000100000005fffffffe');
  });
});

describe('unencrypted header bytes', () => {
  const data = fromHex('00'.repeat(40));
  it('VP8: 10 on keyframes, 3 on delta frames', () => {
    expect(unencryptedBytes('vp8', data, true)).toBe(10);
    expect(unencryptedBytes('vp8', data, false)).toBe(3);
  });
  it('Opus: 1', () => expect(unencryptedBytes('opus', data, false)).toBe(1));
  it('VP9 and AV1: 0', () => {
    expect(unencryptedBytes('vp9', data, true)).toBe(0);
    expect(unencryptedBytes('av1', data, true)).toBe(0);
  });
  it('H.264: through the first slice NALU header + 1, parameter sets clear', () => {
    // 4-byte start code SPS (11 bytes) + PPS (8) + IDR header at offset 23.
    const frame = fromHex('000000016742c01fda0140' + '0000000168ce3c80' + '0000000165888400');
    expect(h264UnencryptedBytes(frame)).toBe(23 + 2);
    // 3-byte start code, non-IDR slice.
    expect(h264UnencryptedBytes(fromHex('000001419a00ff'))).toBe(5);
    // No slice: nothing kept clear (libwebrtc behaviour).
    expect(h264UnencryptedBytes(fromHex('0000000167420000'))).toBe(0);
  });
  it('never exceeds the frame', () => {
    expect(unencryptedBytes('vp8', fromHex('aabb'), true)).toBe(2);
  });
});

describe('RBSP escaping', () => {
  it('round-trips and removes start-code lookalikes', () => {
    const raw = fromHex('0000010000020000030000ff00');
    const escaped = writeRbsp(raw);
    expect(toHex(escaped)).toBe('0000030100000302000003030000ff00');
    expect(needsRbspUnescaping(escaped)).toBe(true);
    expect(toHex(parseRbsp(escaped))).toBe(toHex(raw));
  });
});

describe('codec detection', () => {
  it('reads mime types and SDP rtpmaps', () => {
    expect(codecFromMimeType('video/VP8')).toBe('vp8');
    expect(codecFromMimeType('video/AV1')).toBe('av1');
    expect(codecFromMimeType('video/rtx')).toBeUndefined();
    expect(
      payloadTypesFromSdp('a=rtpmap:96 VP8/90000\r\na=rtpmap:102 H264/90000\r\na=rtpmap:111 opus/48000/2\r\n'),
    ).toEqual({
      96: 'vp8',
      102: 'h264',
      111: 'opus',
    });
  });
});

describe('FrameCryptorCore', () => {
  const vp8 = { codec: 'vp8' as const, isKeyFrame: false };
  const frame = fromHex('310100' + PAYLOAD);

  function makeCore(sharedKey: boolean, states: Array<[string, string, E2EEState]>, ratchetWindow = 8) {
    return new FrameCryptorCore({
      sharedKey,
      ratchetWindow,
      onStateChanged: (participant, direction, state) => states.push([participant, direction, state]),
    });
  }

  it('round-trips with a shared key', async () => {
    const states: Array<[string, string, E2EEState]> = [];
    const sender = makeCore(true, states);
    const receiver = makeCore(true, states);
    const material = await deriveMaterialFromPassphrase(PASSPHRASE, ROOM_ID);
    await sender.setKey(undefined, material);
    await receiver.setKey(undefined, material);
    const encrypted = await sender.encrypt('alice', frame, vp8, 1, 3000);
    expect(encrypted).not.toBeNull();
    expect(toHex((await receiver.decrypt('alice', encrypted!, vp8))!)).toBe(toHex(frame));
    expect(states).toEqual([
      ['alice', 'encrypt', 'ok'],
      ['alice', 'decrypt', 'ok'],
    ]);
  });

  it('reports missing_key and drops when no key is set, on both sides', async () => {
    const states: Array<[string, string, E2EEState]> = [];
    const sender = makeCore(false, states);
    expect(await sender.encrypt('alice', frame, vp8, 1, 3000)).toBeNull();

    const keyed = makeCore(false, []);
    await keyed.setKey('alice', fromHex(RAW_KEY_HEX), 3);
    const encrypted = (await keyed.encrypt('alice', frame, vp8, 1, 3000))!;
    const receiver = makeCore(false, states);
    await receiver.setKey('alice', fromHex(RAW_KEY_HEX), 0); // wrong index
    expect(await receiver.decrypt('alice', encrypted, vp8)).toBeNull();
    expect(states).toEqual([
      ['alice', 'encrypt', 'missing_key'],
      ['alice', 'decrypt', 'missing_key'],
    ]);
  });

  it('follows a sender that ratcheted, within the window, and adopts the new key', async () => {
    const material = fromHex(RAW_KEY_HEX);
    const sender = makeCore(false, []);
    await sender.setKey('alice', material);
    for (let i = 0; i < 3; i++) await sender.ratchet('alice');

    const ratcheted: number[] = [];
    const states: Array<[string, string, E2EEState]> = [];
    const receiver = new FrameCryptorCore({
      sharedKey: false,
      onStateChanged: (p, d, s) => states.push([p, d, s]),
      onKeyRatcheted: (_p, index) => ratcheted.push(index),
    });
    await receiver.setKey('alice', material);
    const encrypted = (await sender.encrypt('alice', frame, vp8, 9, 100))!;
    expect(toHex((await receiver.decrypt('alice', encrypted, vp8))!)).toBe(toHex(frame));
    expect(ratcheted).toEqual([0]);
    // The ratcheted key is now the receiver's: the next frame needs no search.
    const next = (await sender.encrypt('alice', frame, vp8, 9, 200))!;
    expect(await receiver.decrypt('alice', next, vp8)).not.toBeNull();
    expect(ratcheted).toEqual([0]);
    expect(states).toEqual([['alice', 'decrypt', 'ok']]);
  });

  it('gives up beyond the ratchet window with decrypt_failed', async () => {
    const material = fromHex(RAW_KEY_HEX);
    const sender = makeCore(false, []);
    await sender.setKey('alice', material);
    for (let i = 0; i < 3; i++) await sender.ratchet('alice');
    const states: Array<[string, string, E2EEState]> = [];
    const receiver = makeCore(false, states, 2);
    await receiver.setKey('alice', material);
    const encrypted = (await sender.encrypt('alice', frame, vp8, 9, 100))!;
    expect(await receiver.decrypt('alice', encrypted, vp8)).toBeNull();
    expect(states).toEqual([['alice', 'decrypt', 'decrypt_failed']]);
  });

  it('rejects a frame encrypted under a different passphrase', async () => {
    const states: Array<[string, string, E2EEState]> = [];
    const sender = makeCore(true, []);
    const receiver = makeCore(true, states);
    await sender.setKey(undefined, await deriveMaterialFromPassphrase('one', ROOM_ID));
    await receiver.setKey(undefined, await deriveMaterialFromPassphrase('two', ROOM_ID));
    const encrypted = (await sender.encrypt('bob', frame, vp8, 1, 1))!;
    expect(await receiver.decrypt('bob', encrypted, vp8)).toBeNull();
    expect(states).toEqual([['bob', 'decrypt', 'decrypt_failed']]);
  });

  it('passes frames through untouched while disabled (room without e2ee)', async () => {
    const core = makeCore(true, []);
    core.enabled = false;
    expect(await core.encrypt('a', frame, vp8, 1, 1)).toBe(frame);
    expect(await core.decrypt('a', frame, vp8)).toBe(frame);
  });

  it('uses a different salt per room', async () => {
    const a = await deriveMaterialFromPassphrase(PASSPHRASE, 'room_a');
    const b = await deriveMaterialFromPassphrase(PASSPHRASE, 'room_b');
    expect(toHex(a)).not.toBe(toHex(b));
    expect(a.length).toBe(32);
  });
});
