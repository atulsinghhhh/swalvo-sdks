import kotlinx.serialization.json.jsonArray
import kotlinx.serialization.json.jsonObject
import kotlinx.serialization.json.jsonPrimitive
import kotlinx.serialization.json.long
import org.junit.Assert.assertArrayEquals
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertNull
import org.junit.Test
import java.io.File

/**
 * phase5 §3 key schedule and frame format against the cross-SDK vectors
 * (docs/architecture/e2ee-vectors.json, generated by the web SDK). Reads the
 * repo copy when the SDK is built inside the monorepo, else the bundled copy.
 */
class E2eeVectorsTest {
    private val vectors: JsonObject by lazy {
        val repoCopy = File("../../../docs/architecture/e2ee-vectors.json")
        val text = if (repoCopy.isFile) {
            repoCopy.readText()
        } else {
            javaClass.classLoader!!.getResource("e2ee-vectors.json")!!.readText()
        }
        Json.parseToJsonElement(text).jsonObject
    }

    private fun JsonObject.str(key: String) = getValue(key).jsonPrimitive.content
    private fun hex(s: String): ByteArray = ByteArray(s.length / 2) { s.substring(it * 2, it * 2 + 2).toInt(16).toByte() }
    private fun ByteArray.hex(): String = joinToString("") { "%02x".format(it) }

    @Test
    fun passphraseDerivesTheSharedMaterialAndKey() {
        val v = vectors.getValue("passphrase").jsonObject
        val material = E2eeKeyDerivation.materialFromPassphrase(v.str("passphrase"), v.str("roomId"))
        assertEquals(v.str("material"), material.hex())
        assertEquals(v.str("aesKey"), E2eeKeyDerivation.aesKeyFromMaterial(material).hex())
        assertEquals(v.str("salt"), E2eeKeyDerivation.PASSPHRASE_SALT_PREFIX + v.str("roomId"))
    }

    @Test
    fun ratchetStepsMatch() {
        val v = vectors.getValue("ratchet").jsonObject
        var material = hex(v.str("from"))
        for (step in v.getValue("steps").jsonArray) {
            material = E2eeKeyDerivation.ratchet(material)
            assertEquals(step.jsonObject.str("material"), material.hex())
            assertEquals(step.jsonObject.str("aesKey"), E2eeKeyDerivation.aesKeyFromMaterial(material).hex())
        }
    }

    @Test
    fun rawKeyMaterialDerivesTheAesKey() {
        val v = vectors.getValue("rawKey").jsonObject
        assertEquals(v.str("aesKey"), E2eeKeyDerivation.aesKeyFromMaterial(hex(v.str("material"))).hex())
    }

    private fun codecOf(name: String) = when (name) {
        "vp8" -> E2eeCodec.VP8
        "h264" -> E2eeCodec.H264
        "opus" -> E2eeCodec.OPUS
        "vp9" -> E2eeCodec.VP9
        "av1" -> E2eeCodec.AV1
        else -> error("unknown codec $name")
    }

    @Test
    fun framesEncryptByteForByte() {
        val frames = vectors.getValue("frames").jsonObject
        val aesKey = E2eeKeyDerivation.aesKeyFromMaterial(hex(frames.str("keyMaterial")))
        val cases = frames.getValue("cases").jsonArray
        assert(cases.isNotEmpty())
        for (element in cases) {
            val c = element.jsonObject
            val name = c.str("name")
            val codec = codecOf(c.str("codec"))
            val keyframe = c.getValue("isKeyFrame").jsonPrimitive.boolean
            val plaintext = hex(c.str("plaintext"))
            val ssrc = c.getValue("ssrc").jsonPrimitive.long
            val timestamp = c.getValue("timestamp").jsonPrimitive.long
            val sendCount = c.getValue("sendCount").jsonPrimitive.long
            val keyIndex = c.getValue("keyIndex").jsonPrimitive.int

            assertEquals(name, c.getValue("unencryptedBytes").jsonPrimitive.int, E2eeFrameCodec.unencryptedBytes(codec, plaintext, keyframe))
            assertEquals(name, c.str("iv"), E2eeFrameCodec.makeIv(ssrc, timestamp, sendCount).hex())

            val encrypted = E2eeFrameCodec.encrypt(plaintext, codec, keyframe, aesKey, keyIndex, ssrc, timestamp, sendCount)
            assertEquals(name, c.str("encrypted"), encrypted.hex())
            assertEquals(name, keyIndex, E2eeFrameCodec.keyIndexOf(encrypted))

            val opened = E2eeFrameCodec.decrypt(hex(c.str("encrypted")), codec, keyframe, aesKey)
            assertArrayEquals(name, plaintext, opened)
        }
    }

    @Test
    fun wrongKeyFailsAndTheRatchetWindowRecoversANewerKey() {
        val frames = vectors.getValue("frames").jsonObject
        val material = hex(frames.str("keyMaterial"))
        val c = frames.getValue("cases").jsonArray.first().jsonObject
        val plaintext = hex(c.str("plaintext"))

        // Sender ratcheted twice; receiver still holds the original material.
        val senderMaterial = E2eeKeyDerivation.ratchet(E2eeKeyDerivation.ratchet(material))
        val frame = E2eeFrameCodec.encrypt(plaintext, E2eeCodec.VP8, true, E2eeKeyDerivation.aesKeyFromMaterial(senderMaterial), 0, 1, 2, 0)

        assertNull(E2eeFrameCodec.decrypt(frame, E2eeCodec.VP8, true, E2eeKeyDerivation.aesKeyFromMaterial(material)))
        val opened = E2eeFrameCodec.decryptWithRatchet(frame, E2eeCodec.VP8, true, material, ratchetWindow = 8)
        assertNotNull(opened)
        assertArrayEquals(plaintext, opened!!.plaintext)
        assertEquals(2, opened.ratchets)
        assertArrayEquals(senderMaterial, opened.material)

        // Outside the window: dropped (→ decrypt_failed).
        assertNull(E2eeFrameCodec.decryptWithRatchet(frame, E2eeCodec.VP8, true, material, ratchetWindow = 1))
    }

    @Test
    fun rbspEscapingRoundTrips() {
        val raw = byteArrayOf(0, 0, 0, 0, 0, 1, 0, 0, 2, 0, 0, 3, 5, 0, 0)
        val escaped = Rbsp.escape(raw)
        assertEquals("00000300000300010000030200000303050000", escaped.hex())
        assertArrayEquals(raw, Rbsp.unescape(escaped))
    }

    @Test
    fun pbkdf2MatchesRfc7914Vector() {
        // RFC 7914 §11: PBKDF2-HMAC-SHA256("passwd", "salt", 1, 64)
        val out = E2eeKeyDerivation.pbkdf2HmacSha256("passwd".toByteArray(), "salt".toByteArray(), 1, 64)
        assertEquals(
            "55ac046e56e3089fec1691c22544b605f94185216dde0465e68b9d57c20dacbc" +
                "49ca9cccf179b645991664b39d77ef317c71b845b1e30bd509112041d3a19783",
            out.hex(),
        )
    }

    @Test
    fun hkdfMatchesRfc5869Case1() {
        val okm = E2eeKeyDerivation.hkdfSha256(
            hex("0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b"),
            hex("000102030405060708090a0b0c"),
            hex("f0f1f2f3f4f5f6f7f8f9"),
            42,
        )
        assertEquals("3cb25f25faacd57a90434f64d0362f2a2d2d0a90cf1a5a4c5db02d56ecc4c5bf34007208d5b887185865", okm.hex())
    }
}
